"""Bonsai adapter for an explicitly started, loopback-only llama.cpp server.

Server lifecycle belongs to backend. No hosted inference endpoints, proxying,
redirects or legal citations generated by the model are accepted.
"""
import base64
import ipaddress
import json
from pathlib import Path
from urllib.parse import urlsplit
import cv2
import httpx


def checked_endpoint(url):
    parsed=urlsplit(url)
    try:loopback=ipaddress.ip_address(parsed.hostname or '').is_loopback
    except ValueError:loopback=False
    if parsed.scheme!='http' or not loopback or parsed.username or parsed.password or parsed.query or parsed.fragment:
        raise ValueError('Bonsai inference endpoint must be an HTTP loopback address')
    return url.rstrip('/')


class BonsaiSession:
    def __init__(self,config,transport=None):
        settings=json.loads(Path(config).read_text())
        endpoint=checked_endpoint(settings['endpoint'])
        self.model=settings.get('model_alias','forte-bonsai')
        self.client=httpx.Client(base_url=endpoint,timeout=120,trust_env=False,
                                 follow_redirects=False,transport=transport)
        self.last_usage={}

    def close(self):
        self.client.close()

    def infer(self,window,prompt):
        content=[{'type':'text','text':prompt}]
        for frame in window:
            image=frame.bgr
            h,w=image.shape[:2]
            if max(h,w)>448:image=cv2.resize(image,(round(w*448/max(h,w)),round(h*448/max(h,w))))
            ok,data=cv2.imencode('.jpg',image,[cv2.IMWRITE_JPEG_QUALITY,85])
            if not ok:raise ValueError('Model input image encoding failed')
            content.extend([{'type':'text','text':f'Timestamp {frame.time:.3f} seconds'},
                {'type':'image_url','image_url':{'url':'data:image/jpeg;base64,'+base64.b64encode(data).decode()}}])
        response=self.client.post('/v1/chat/completions',json={'model':self.model,
            'messages':[{'role':'user','content':content}],
            'temperature':0,'max_tokens':400,'response_format':{'type':'json_object'},
            'chat_template_kwargs':{'enable_thinking':False}})
        response.raise_for_status()
        data=response.json();choices=data.get('choices')
        if not isinstance(choices,list) or len(choices)!=1:raise ValueError('Model response has invalid choices')
        choice=choices[0]
        if choice.get('finish_reason')!='stop':raise ValueError('Truncated model response or unsuccessful generation')
        raw=choice.get('message',{}).get('content')
        if not isinstance(raw,str) or not raw.strip():raise ValueError('Model response has no JSON content')
        self.last_usage=data.get('usage',{})
        return raw


def analyze_bonsai(frames,model_path,rules,progress):
    from ml.qwen import analyze_session
    # Configuration is a local file; endpoint validation runs before any request.
    session=BonsaiSession(model_path)
    try:return analyze_session(frames,session,rules,progress)
    finally:session.close()
