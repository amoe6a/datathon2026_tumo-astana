"""Install dedicated Linux systemd user units; never starts or publishes them."""
import argparse
import json
import os
from pathlib import Path
import re
import secrets
import sys

from app.config import ROOT
from scripts.launch_bonsai import command as native_command

HEADER = '# Generated by Forte Review scripts.install_service\n'


def quoted(value, specifiers=True):
    value = str(value)
    if specifiers:
        value = value.replace('%', '%%')
    return json.dumps(value, ensure_ascii=False)


def install(args):
    if sys.platform != 'linux':
        raise RuntimeError('systemd user services require Linux')
    if not re.fullmatch(r'forte-[a-z0-9-]+', args.name):
        raise ValueError('Use a dedicated service name beginning with forte-')
    python = Path(args.python).absolute()
    if not python.is_file():
        raise ValueError('Python interpreter is missing')
    runtime = Path(args.runtime or ROOT/'runtime'/args.name).resolve()
    unit_dir = Path(os.environ.get('XDG_CONFIG_HOME', Path.home()/'.config'))/'systemd/user'
    api_name = args.name + '.service'
    native_name = args.name + '-model.service'
    names = [api_name] + ([native_name] if args.engine == 'bonsai' else [])
    for name in names:
        target = unit_dir/name
        if target.exists() and not target.read_text(encoding='utf-8').startswith(HEADER):
            raise ValueError('Existing service is not owned by this installer: ' + name)
    runtime.mkdir(parents=True, exist_ok=True, mode=0o700)
    runtime.chmod(0o700)
    key_path = runtime/'access-key.txt'
    if not key_path.exists():
        with key_path.open('x', encoding='utf-8') as stream:
            stream.write(secrets.token_urlsafe(32))
    key_path.chmod(0o600)
    key = key_path.read_text(encoding='utf-8').strip()
    if not re.fullmatch(r'[A-Za-z0-9_-]{16,}', key):
        raise ValueError('Service key must be a random URL-safe token of at least 16 characters')
    env = {'FORTE_API_KEY': key, 'FORTE_RUNTIME': str(runtime),
           'FORTE_ENGINE': args.engine, 'FORTE_MODEL': str(ROOT/'models/demo.npz'),
           'HF_HUB_OFFLINE': '1', 'TRANSFORMERS_OFFLINE': '1', 'HF_HUB_DISABLE_TELEMETRY': '1'}
    api = [str(python), '-m', 'uvicorn', 'app.main:create_app', '--factory',
           '--host', '127.0.0.1', '--port', str(args.port), '--workers', '1']
    units = {}
    dependencies = ''
    pre = ''
    if args.engine == 'bonsai':
        if not args.config or not args.native_binary:
            raise ValueError('Bonsai requires --config and --native-binary')
        config = Path(args.config).resolve()
        native = native_command(config, args.native_binary) + ['--log-disable']
        env['FORTE_MODEL'] = str(config)
        api = [str(python), '-m', 'scripts.serve_bonsai', '--config', str(config),
               '--runtime', str(runtime), '--port', str(args.port)]
        dependencies = f'Wants={native_name}\nAfter={native_name}\n'
        pre = 'ExecStartPre=' + ' '.join(quoted(v) for v in
                [python, '-m', 'scripts.wait_native', '--config', config]) + '\n'
        units[native_name] = HEADER + (
            '[Unit]\nDescription=Forte Review local Bonsai model\n'
            '[Service]\nType=exec\nWorkingDirectory=' + str(ROOT).replace('%', '%%') + '\n'
            'ExecStart=' + ' '.join(quoted(v) for v in native) + '\n'
            'Restart=on-failure\nRestartSec=3\nTimeoutStopSec=20\n'
            'KillMode=control-group\nUMask=0077\n'
            'StandardOutput=append:' + str(runtime/'native.log') + '\nStandardError=inherit\n'
            '[Install]\nWantedBy=default.target\n')
    elif not (ROOT/'models/demo.npz').is_file():
        raise ValueError('Generate synthetic fixtures first: python -m scripts.make_demo')
    env_path = runtime/'service.env'
    env_path.write_text(''.join(k+'='+quoted(v, False)+'\n' for k,v in env.items()), encoding='utf-8')
    env_path.chmod(0o600)
    units[api_name] = HEADER + (
        '[Unit]\nDescription=Forte Review ' + args.engine + ' API\n' + dependencies +
        '[Service]\nType=exec\nWorkingDirectory=' + str(ROOT).replace('%', '%%') + '\n'
        'EnvironmentFile=' + str(env_path).replace('%', '%%') + '\n' + pre +
        'ExecStart=' + ' '.join(quoted(v) for v in api) + '\n'
        'Restart=on-failure\nRestartSec=3\nTimeoutStartSec=200\nTimeoutStopSec=20\n'
        'KillMode=control-group\nUMask=0077\n'
        'StandardOutput=append:' + str(runtime/'api.log') + '\nStandardError=inherit\n'
        '[Install]\nWantedBy=default.target\n')
    unit_dir.mkdir(parents=True, exist_ok=True)
    for name, source in units.items():
        (unit_dir/name).write_text(source, encoding='utf-8')
    manifest = {'engine': args.engine, 'port': args.port, 'runtime': str(runtime),
                'key_file': str(key_path), 'python': str(python),
                'units': [str(unit_dir/name) for name in units], 'public': False}
    (runtime/'service-manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    print(json.dumps(manifest, indent=2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--name', required=True)
    parser.add_argument('--engine', choices=['demo', 'bonsai'], required=True)
    parser.add_argument('--port', type=int, required=True)
    parser.add_argument('--python', default=sys.executable)
    parser.add_argument('--runtime')
    parser.add_argument('--config')
    parser.add_argument('--native-binary')
    args = parser.parse_args()
    if not 1024 <= args.port <= 65535:
        parser.error('Choose a port between 1024 and 65535')
    install(args)


if __name__ == '__main__':
    main()
